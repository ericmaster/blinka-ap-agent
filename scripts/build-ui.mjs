// Generates src/server/ui.mjs (inlined HTML) and src/server/seed.mjs (mock email inbox + WhatsApp chat seeded from data/curated).
// Workers have no filesystem, so everything is inlined. Fictional data only.
import { readFileSync, writeFileSync } from "node:fs";
import { coverEmail } from "../src/gen/generator.mjs";
import { rng, hash } from "../src/gen/format.mjs";
import { UI_ES } from "../src/i18n/ui.mjs";
import { reasonsClientJs } from "../src/i18n/reasons.mjs";
// i18n: the UI dictionary and the decision-reason templates are inlined where ui.html has /*I18N*/
const html = readFileSync("src/server/ui.html", "utf8"), i18n = `const I18N={es:{ui:${JSON.stringify(UI_ES)}}};\n${reasonsClientJs()}`;
if (!html.includes("/*I18N*/")) throw new Error("ui.html lost its /*I18N*/ marker");
writeFileSync("src/server/ui.mjs", "// generated by scripts/build-ui.mjs\nexport const UI = " + JSON.stringify(html.replace("/*I18N*/", () => i18n)) + ";\n");
const man = JSON.parse(readFileSync("data/curated/manifest.json", "utf8"));
const emails = [], chats = [], blobs = {};
const PHOTO = { es: "te mando foto de la factura", en: "photo of the invoice", pt: "foto da fatura" };
const short = (n) => n.replace(/ (S\.?A\.?S|S\.A\. de C\.V\.|Ltda|SAC|SpA|S\.C\.|\(contractor\))\.?$/i, "").replace(/ Serviços$/, "");
const addr = (v) => { const mm = v.match(/^(.*?)\s*<([^>]+)>$/); return mm ? { name: mm[1].replace(/^"|"$/g, ""), email: mm[2] } : { name: null, email: v }; };
const pdfAtt = (m, file) => { const id = `a-${m.id}`; blobs[id] = readFileSync(`data/curated/${file}`).toString("base64"); return [{ id, name: `${m.number ?? m.id}.pdf`, type: "application/pdf" }]; };
man.forEach((m, i) => {
  const at = new Date(Date.UTC(2026, 9, 16, 13, 0) + i * 7 * 60000).toISOString();
  if (m.format === "email") {
    // vendor email with the invoice PDF attached (the mailbox processes the PDF; the .email.txt text is the same invoice for text-only tests)
    const raw = readFileSync(`data/curated/${m.file}`, "utf8"), cut = raw.indexOf("\n\n"), head = raw.slice(0, cut), body = raw.slice(cut + 2);
    const h = Object.fromEntries(head.split("\n").map((l) => [l.split(":")[0].toLowerCase(), l.slice(l.indexOf(":") + 1).trim()])), f = addr(h.from);
    emails.push({ id: `m-${m.id}`, at, from: f.email, fromName: f.name ?? m.payeeName, subject: h.subject,
      body: m.attachment ? body.replace(/\n*📎[^\n]*\s*$/, "").trimEnd() : body, attachments: m.attachment ? pdfAtt(m, m.attachment) : [] });
  } else if (m.format === "pdf") {
    const c = coverEmail(m, rng(hash(m.id)));
    emails.push({ id: `m-${m.id}`, at, from: c.from, fromName: c.fromName, subject: c.subject, body: c.body, attachments: pdfAtt(m, m.file) });
  } else if (m.format === "image") {
    const id = `a-${m.id}`; blobs[id] = readFileSync(`data/curated/${m.file}`).toString("base64");
    chats.push({ id: `w-${m.id}`, at, from: short(m.payeeName), text: PHOTO[m.lang], attachment: { id, name: `${m.number}.jpg`, type: "image/jpeg" } });
  } else {
    const raw = readFileSync(`data/curated/${m.file}`, "utf8"), mm = raw.match(/^\[[^\]]+\]\s*([^:]+):\s*([\s\S]*)$/);
    chats.push({ id: `w-${m.id}`, at, from: `${mm[1]} · ${short(m.payeeName)}`, text: mm[2] });
  }
});
writeFileSync("src/server/seed.mjs", "// generated by scripts/build-ui.mjs from data/curated (fictional data)\nexport const SEED = " +
  JSON.stringify({ emails, chats }) + ";\nexport const SEED_BLOBS = " + JSON.stringify(blobs) + ";\n");
console.log(`ui + seed: ${emails.length} emails, ${chats.length} chats, ${Object.keys(blobs).length} attachments`);
