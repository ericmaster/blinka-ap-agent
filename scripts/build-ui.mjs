// Inline ui.html and the curated demo files into JS modules (Workers have no filesystem).
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
writeFileSync("src/server/ui.mjs", "// generated by scripts/build-ui.mjs\nexport const UI = " + JSON.stringify(readFileSync("src/server/ui.html", "utf8")) + ";\n");
const files = readdirSync("data/curated").filter((f) => /\.(email\.txt|chat\.txt|pdf|png)$/.test(f)).sort();
const demo = Object.fromEntries(files.map((f) => [f, readFileSync(`data/curated/${f}`).toString("base64")]));
writeFileSync("src/server/demo.mjs", "// generated by scripts/build-ui.mjs from data/curated (fictional data)\nexport const DEMO = " + JSON.stringify(demo) + ";\n");
console.log("ui + demo:", files.length, "files");
