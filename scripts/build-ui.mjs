// Generates src/server/ui.mjs (inlined HTML) and src/server/seed.mjs (mock email inbox + WhatsApp chat seeded from data/curated).
// Workers have no filesystem, so everything is inlined. Fictional data only.
import { readFileSync, writeFileSync } from "node:fs";
writeFileSync("src/server/ui.mjs", "// generated by scripts/build-ui.mjs\nexport const UI = " + JSON.stringify(readFileSync("src/server/ui.html", "utf8")) + ";\n");
const man = JSON.parse(readFileSync("data/curated/manifest.json", "utf8"));
const emails = [], chats = [], blobs = {};
const ATT = { es: "Adjunto la factura", en: "Please find attached invoice", pt: "Segue em anexo a fatura" };
const PHOTO = { es: "te mando foto de la factura", en: "photo of the invoice", pt: "foto da fatura" };
const short = (n) => n.replace(/ (S\.?A\.?S|S\.A\. de C\.V\.|Ltda|SAC|SpA|S\.C\.|\(contractor\))\.?$/i, "").replace(/ Serviços$/, "");
man.forEach((m, i) => {
  const at = new Date(Date.UTC(2026, 9, 16, 13, 0) + i * 7 * 60000).toISOString();
  const fromAddr = "billing@" + m.payeeName.toLowerCase().replace(/[^a-z]+/g, "").slice(0, 12) + ".example";
  if (m.format === "email") {
    const raw = readFileSync(`data/curated/${m.file}`, "utf8"), [head, ...rest] = raw.split("\n\n");
    const h = Object.fromEntries(head.split("\n").map((l) => [l.split(":")[0].toLowerCase(), l.slice(l.indexOf(":") + 1).trim()]));
    emails.push({ id: `m-${m.id}`, at, from: h.from, fromName: m.payeeName, subject: h.subject, body: rest.join("\n\n"), attachments: [] });
  } else if (m.format === "pdf") {
    const id = `a-${m.id}`; blobs[id] = readFileSync(`data/curated/${m.file}`).toString("base64");
    emails.push({ id: `m-${m.id}`, at, from: fromAddr, fromName: m.payeeName, subject: `${m.number}`, body: `${ATT[m.lang]} ${m.number}.\n\n${m.payeeName}`,
      attachments: [{ id, name: `${m.number}.pdf`, type: "application/pdf" }] });
  } else if (m.format === "image") {
    const id = `a-${m.id}`; blobs[id] = readFileSync(`data/curated/${m.file}`).toString("base64");
    chats.push({ id: `w-${m.id}`, at, from: short(m.payeeName), text: PHOTO[m.lang], attachment: { id, name: `${m.number}.png`, type: "image/png" } });
  } else {
    const raw = readFileSync(`data/curated/${m.file}`, "utf8"), mm = raw.match(/^\[[^\]]+\]\s*([^:]+):\s*([\s\S]*)$/);
    chats.push({ id: `w-${m.id}`, at, from: `${mm[1]} · ${short(m.payeeName)}`, text: mm[2] });
  }
});
writeFileSync("src/server/seed.mjs", "// generated by scripts/build-ui.mjs from data/curated (fictional data)\nexport const SEED = " +
  JSON.stringify({ emails, chats }) + ";\nexport const SEED_BLOBS = " + JSON.stringify(blobs) + ";\n");
console.log(`ui + seed: ${emails.length} emails, ${chats.length} chats, ${Object.keys(blobs).length} attachments`);
